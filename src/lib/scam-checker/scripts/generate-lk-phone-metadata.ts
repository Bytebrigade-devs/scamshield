/** Offline reproducible generation: node code/preprocess/scripts/generate-lk-phone-metadata.ts [--check].
 *
 * The vendored JSON is the reviewed source (SHA-256 pinned below). No network access and no
 * npm dependency is used here or at runtime — the approved libphonenumber-js metadata subset
 * is reviewed once, committed, and generated into a typed constant.
 *
 * Refresh procedure (reviewed decision, never silent):
 *   1. Download the pinned libphonenumber-js metadata.max.json version.
 *   2. Verify the artifact SHA-256 recorded in provenance.sourceArtifactSha256.
 *   3. Extract the "LK" entry: [callingCode, internationalPrefix, nationalNumberPattern,
 *      possibleLengths, formats, trunkPrefix, …, types[]] — types[0] fixed line, types[1] mobile.
 *   4. Update vendor/lk-phonenumber-metadata.json, re-run this script, and record the change
 *      in a dated evidence document.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** SHA-256 of the reviewed vendored source file. A mismatch is a hard failure. */
export const VENDORED_SHA256 = 'b6fa2d2905c77ce9cf67a971455fbb942865793bf4c7377d5f2d6571fa5b9664';

interface VendoredMetadata {
  country: { iso: string; name: string };
  provenance: {
    sourceName: string; sourceVersion: string; sourceLicence: string; sourceUrl: string;
    upstream: string; metadataFormatVersion: number; downloadedAt: string;
    sourceArtifactSha256: string; extractedAt: string; reviewedBy: string;
  };
  numbering: {
    countryCallingCode: string; trunkPrefix: string; internationalPrefix: string;
    nationalNumberPattern: string; possibleLengths: number[]; mobilePattern: string; fixedLinePattern: string;
  };
  limits: string[];
}

const source = fileURLToPath(new URL('../vendor/lk-phonenumber-metadata.json', import.meta.url));
const bytes = readFileSync(source);
const actual = createHash('sha256').update(bytes).digest('hex');
if (actual.toLowerCase() !== VENDORED_SHA256) {
  throw new Error(`Vendored LK phone metadata integrity failure: expected ${VENDORED_SHA256}, got ${actual}`);
}
const metadata = JSON.parse(bytes.toString('utf8')) as VendoredMetadata;
if (metadata.country.iso !== 'LK') throw new Error('Vendored metadata is not Sri Lanka (LK)');

const { numbering, provenance } = metadata;
const string = (value: string): string => JSON.stringify(value);
const output = `// Generated by scripts/generate-lk-phone-metadata.ts. DO NOT hand-edit.
// Source: ${provenance.sourceName} ${provenance.sourceVersion} metadata (${provenance.sourceLicence}); ${provenance.upstream}
// Artifact SHA-256 ${provenance.sourceArtifactSha256}
// Metadata format version ${provenance.metadataFormatVersion} · extracted ${provenance.extractedAt}
// LIMITS: shape classification only — never an allocation, reachability, subscriber or operator claim.
export const LK_NUMBERING = {
  countryCallingCode: ${string(numbering.countryCallingCode)},
  trunkPrefix: ${string(numbering.trunkPrefix)},
  internationalPrefix: ${string(numbering.internationalPrefix)},
  nationalNumberPattern: ${string(numbering.nationalNumberPattern)},
  possibleLengths: [${numbering.possibleLengths.join(', ')}] as const,
  mobilePattern: ${string(numbering.mobilePattern)},
  fixedLinePattern: ${string(numbering.fixedLinePattern)},
  source: {
    name: ${string(provenance.sourceName)},
    version: ${string(provenance.sourceVersion)},
    licence: ${string(provenance.sourceLicence)},
    artifactSha256: ${string(provenance.sourceArtifactSha256)},
    vendoredSha256: ${string(VENDORED_SHA256)},
    reviewedAt: ${string(provenance.extractedAt)}
  }
} as const;
`;

const destination = fileURLToPath(new URL('../lk-phone-metadata.generated.ts', import.meta.url));
if (process.argv.includes('--stdout')) {
  process.stdout.write(output);
} else if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Generated LK phone metadata is out of date');
} else {
  writeFileSync(destination, output);
}
if (!process.argv.includes('--stdout')) console.log(`LK phone metadata: ${numbering.countryCallingCode} ${numbering.possibleLengths.join('/')} digits; integrity verified (${VENDORED_SHA256.slice(0, 12)}…).`);

/** Offline reproducible generation: node code/ui/scripts/generate-confusables.ts [--check].
 * Unicode data and Unicode License V3 are vendored beside the output; no network or npm.
 * The source code point is limited by Unicode 18 Scripts.txt; targets stay complete,
 * including multi-codepoint and other-script targets required by UTS #39 skeletons.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../vendor/unicode-18.0.0/', import.meta.url);
export const CONFUSABLES_SHA256 = '6ED3EE967C9DFDF6677D563C9985182FBC50A2EFB7D6059CD57B2E2CE18F5B92';
const SCRIPTS_SHA256 = '0071FD81B6AEAE25F6E8BCE8EFEC3066A6476A91B49BDB2F52DC76E817862A6A';
const supported = new Set(['Latin', 'Greek', 'Cyrillic', 'Common', 'Inherited']);
function pinned(name: string, sha: string): string {
  const bytes = readFileSync(new URL(name, root));
  if (createHash('sha256').update(bytes).digest('hex').toUpperCase() !== sha) throw new Error(`Unicode source integrity failure: ${name}`);
  return bytes.toString('utf8');
}
const scripts = pinned('Scripts.txt', SCRIPTS_SHA256);
const ranges: [number, number, string][] = [];
for (const line of scripts.split('\n')) {
  const match = /^([A-F0-9]+)(?:\.\.([A-F0-9]+))?\s*;\s*(\w+)/.exec(line);
  if (match && supported.has(match[3])) ranges.push([parseInt(match[1], 16), parseInt(match[2] ?? match[1], 16), match[3]]);
}
ranges.sort((a, b) => a[0] - b[0]);
const mappings: [string, string][] = [];
for (const line of pinned('confusables.txt', CONFUSABLES_SHA256).split('\n')) {
  const match = /^([A-F0-9]+)\s*;\s*([A-F0-9 ]+)\s*;\s*MA\s*#/.exec(line);
  if (!match) continue;
  const cp = parseInt(match[1], 16);
  if (!ranges.some(([start, end]) => cp >= start && cp <= end)) continue;
  mappings.push([String.fromCodePoint(cp), String.fromCodePoint(...match[2].trim().split(/\s+/).map(hex => parseInt(hex, 16)))]);
}
mappings.sort((a, b) => a[0].codePointAt(0)! - b[0].codePointAt(0)!);
const output = `// Generated by scripts/generate-confusables.ts. DO NOT hand-edit.\n// Unicode 18.0.0; https://www.unicode.org/Public/18.0.0/security/confusables.txt\n// SHA256 ${CONFUSABLES_SHA256}\n// Copyright Unicode, Inc.; Unicode License V3: vendor/unicode-18.0.0/LICENSE.txt\nexport const UNICODE_VERSION = '18.0.0';\nexport const SCRIPT_RANGES: readonly (readonly [number, number, string])[] = ${JSON.stringify(ranges)};\nexport const CONFUSABLE_MAPPINGS: readonly (readonly [string, string])[] = ${JSON.stringify(mappings)};\n`;
const destination = new URL('../confusables.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Generated Unicode subset is out of date');
} else writeFileSync(destination, output);
console.log(`Unicode 18.0.0: ${mappings.length} mappings, ${ranges.length} script ranges; integrity verified.`);

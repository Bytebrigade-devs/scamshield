/**
 * Regenerate the app-served copy of the checker UI.
 *
 * Source of truth: `src/lib/scam-checker/ui/public/` (byte-pinned, tested).
 * Outputs:
 *   - `public/checker/*`  — browser assets with `from '/x.js'` rewritten to `from '/checker/x.js'`
 *   - `public/fonts/*.woff2` — fonts stay at the root path the stylesheet already expects
 *   - `src/app/checker/shell.generated.ts` — the HTML shell returned by `/checker`
 *
 * Usage:
 *   node src/lib/scam-checker/ui/scripts/sync-public.ts          # write
 *   node src/lib/scam-checker/ui/scripts/sync-public.ts --check  # verify only (used by tests/CI)
 *
 * No network, no dependencies. The mirror test runs `--check` so the served copy cannot drift.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', 'public');
const repoRoot = join(here, '..', '..', '..', '..', '..');
const checkerTarget = join(repoRoot, 'public', 'checker');
const fontsTarget = join(repoRoot, 'public', 'fonts');
const shellTarget = join(repoRoot, 'src', 'app', 'checker', 'shell.generated.ts');

/** Honest demo notice injected into the served shell; never shown by the standalone server. */
const DEMO_NOTICE =
  '<p role="note" style="margin:0;padding:8px 16px;background:#fff4e5;border-bottom:1px solid #f0d9b5;'
  + 'font:14px/1.4 system-ui,sans-serif;color:#5c3d00">Demo build — local pattern checks only. '
  + 'No sign-in, no saved history on the server, and no AI analysis is configured.</p>';

const binaryExtensions = new Set(['.woff2', '.ttf', '.png', '.jpg', '.ico']);

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

/** Asset rewrites applied only to the served copy. */
function transform(rel: string, bytes: Buffer): Buffer {
  if (binaryExtensions.has(rel.slice(rel.lastIndexOf('.')))) return bytes;
  let text = bytes.toString('utf8');
  if (rel.endsWith('.js')) {
    text = text.replaceAll("from '/", "from '/checker/").replaceAll("import('/", "import('/checker/");
  }
  if (rel === 'index.html' || rel === 'checker-index.html') {
    text = text.replaceAll('href="/', 'href="/checker/').replaceAll('src="/', 'src="/checker/');
    text = text.replace('<body>', `<body>\n${DEMO_NOTICE}`);
  }
  return Buffer.from(text, 'utf8');
}

interface Output { path: string; bytes: Buffer }

function build(): Output[] {
  const outputs: Output[] = [];
  for (const file of walk(source)) {
    const rel = relative(source, file).replaceAll('\\', '/');
    const bytes = readFileSync(file);
    if (rel.startsWith('fonts/')) {
      // The stylesheet expects /fonts/*; the repo already carries Plus Jakarta Sans there.
      if (rel.endsWith('.woff2')) outputs.push({ path: join(fontsTarget, rel.slice('fonts/'.length)), bytes });
      continue;
    }
    outputs.push({ path: join(checkerTarget, rel), bytes: transform(rel, bytes) });
  }
  const html = readFileSync(join(source, 'index.html'));
  const shell = transform('index.html', html).toString('utf8');
  outputs.push({
    path: shellTarget,
    bytes: Buffer.from(
      '// Generated by src/lib/scam-checker/ui/scripts/sync-public.ts. DO NOT hand-edit.\n'
      + '// Regenerate with: node src/lib/scam-checker/ui/scripts/sync-public.ts\n'
      + `export const CHECKER_SHELL = ${JSON.stringify(shell)};\n`,
      'utf8',
    ),
  });
  return outputs;
}

const digest = (bytes: Buffer): string => createHash('sha256').update(bytes).digest('hex');
const outputs = build();
const check = process.argv.includes('--check');

if (check) {
  const stale: string[] = [];
  for (const output of outputs) {
    if (!existsSync(output.path) || digest(readFileSync(output.path)) !== digest(output.bytes)) {
      stale.push(relative(repoRoot, output.path).replaceAll('\\', '/'));
    }
  }
  if (stale.length > 0) {
    console.error(`Served checker copy is out of date: ${stale.join(', ')}`);
    console.error('Run: node src/lib/scam-checker/ui/scripts/sync-public.ts');
    process.exit(1);
  }
  console.log(`Served checker copy verified (${outputs.length} files).`);
} else {
  for (const output of outputs) {
    mkdirSync(dirname(output.path), { recursive: true });
    writeFileSync(output.path, output.bytes);
  }
  console.log(`Wrote ${outputs.length} files for the served checker copy.`);
}
